"""Turn the registry into labelled cases and the files that hold them."""

import json
import random
from pathlib import Path

from app.schemas.eval_case import EvalCase, EvalSplit
from tests.evals.generator.kit import Kit
from tests.evals.generator.payer_rules import RULES
from tests.evals.generator.registry import ENTRIES, Entry

DEFAULT_SEED = 42
CATALOG_NAME = "CATALOG.md"
_ID_PREFIX = {EvalSplit.DEV: "DEV", EvalSplit.LOCKED: "LOCK"}


def build_cases(seed: int = DEFAULT_SEED) -> list[EvalCase]:
    """Every generated case, validated, in case-ID order within each split."""
    cases: list[EvalCase] = []
    for split in EvalSplit:
        entries = [entry for entry in ENTRIES if entry.split is split]
        # Shuffle so that neighbouring IDs do not share a scenario or an answer.
        random.Random(f"{seed}:order:{split.value}").shuffle(entries)
        cases.extend(
            _build_case(entry, f"{_ID_PREFIX[split]}-{number:03d}", seed)
            for number, entry in enumerate(entries, start=1)
        )
    return cases


def _build_case(entry: Entry, case_id: str, seed: int) -> EvalCase:
    built = entry.build(Kit(seed, entry.key, entry.payer), RULES[entry.payer])
    return EvalCase.model_validate(
        {
            "case_id": case_id,
            "split": entry.split,
            "scenario": entry.key,
            "tags": built.tags,
            "as_of_date": built.as_of_date,
            "input": built.input,
            "expected": {
                "action": built.action,
                "acceptable_alternatives": built.alternatives,
                "relevant_clause_ids": built.clauses,
                "supporting_evidence": built.evidence,
                "missing_evidence": built.missing,
                "expected_correction": built.correction,
                "rationale": built.rationale,
            },
        }
    )


def render_files(cases: list[EvalCase]) -> dict[str, str]:
    """File contents keyed by path relative to the cases directory."""
    files = {
        f"{case.split.value}/{case.case_id}.json": json.dumps(
            case.model_dump(mode="json"), indent=2, ensure_ascii=False
        )
        + "\n"
        for case in cases
    }
    for split in EvalSplit:
        in_split = [case for case in cases if case.split is split]
        files[f"{split.value}/{CATALOG_NAME}"] = _render_catalog(split, in_split)
    return files


def _render_catalog(split: EvalSplit, cases: list[EvalCase]) -> str:
    lines = [
        f"# {split.value.capitalize()} cases: review catalog",
        "",
        "Generated by `python -m tests.evals.generator`. Do not edit: change the scenario "
        "and regenerate.",
        "",
        f"{len(cases)} generated cases. Tick each one once its label has been checked.",
        "",
    ]
    for case in cases:
        expected = case.expected
        action = expected.action.value if expected.action else "REJECT (invalid input)"
        denial = case.input["denial"]
        lines += [
            f"## {case.case_id}: {action}",
            "",
            f"- Scenario: `{case.scenario}`",
            f"- Payer: {case.input['claim']['payer_id']}, reason code {denial['carc_code']}",
        ]
        if expected.acceptable_alternatives:
            alternatives = ", ".join(a.value for a in expected.acceptable_alternatives)
            lines.append(f"- Also acceptable: {alternatives}")
        if expected.relevant_clause_ids:
            lines.append(f"- Clauses: {', '.join(expected.relevant_clause_ids)}")
        if expected.expected_correction:
            lines.append(f"- Correction: {expected.expected_correction}")
        if expected.missing_evidence:
            lines.append(f"- Missing: {'; '.join(expected.missing_evidence)}")
        if case.tags:
            lines.append(f"- Tags: {', '.join(case.tags)}")
        lines += [f"- Why: {expected.rationale}", "- [ ] Label checked", ""]
    return "\n".join(lines)


def write_files(files: dict[str, str], cases_dir: Path) -> None:
    """Replace the generated files, leaving hand-written cases in place."""
    for split in EvalSplit:
        split_dir = cases_dir / split.value
        split_dir.mkdir(parents=True, exist_ok=True)
        for stale in split_dir.glob(f"{_ID_PREFIX[split]}-*.json"):
            stale.unlink()
    for relative_path, content in files.items():
        (cases_dir / relative_path).write_text(content, encoding="utf-8", newline="\n")


def stale_files(files: dict[str, str], cases_dir: Path) -> list[str]:
    """Paths whose content on disk differs from what the generator produces now."""
    stale: list[str] = []
    for relative_path, content in files.items():
        path = cases_dir / relative_path
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            stale.append(relative_path)
    return sorted(stale)
